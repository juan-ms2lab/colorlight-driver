"""Tiny 3x5 bitmap font (from panel-games' Resurrection), drawn at integer scales for crisp LED text."""

GLYPHS = {
    "0": "111101101101111", "1": "010110010010111", "2": "111001111100111",
    "3": "111001111001111", "4": "101101111001001", "5": "111100111001111",
    "6": "111100111101111", "7": "111001001001001", "8": "111101111101111",
    "9": "111101111001111",
    "A": "010101111101101", "B": "110101110101110", "C": "011100100100011",
    "D": "110101101101110", "E": "111100110100111", "F": "111100110100100",
    "G": "011100101101011", "H": "101101111101101", "I": "111010010010111",
    "J": "001001001101010", "K": "101101110101101", "L": "100100100100111",
    "M": "101111111101101", "N": "110101101101101", "O": "010101101101010",
    "P": "110101110100100", "Q": "010101101110011", "R": "110101110101101",
    "S": "011100010001110", "T": "111010010010010", "U": "101101101101111",
    "V": "101101101101010", "W": "101101111111101", "X": "101101010101101",
    "Y": "101101010010010", "Z": "111001010100111",
    " ": "000000000000000", "!": "010010010000010", ":": "000010000010000",
    "-": "000000111000000", ".": "000000000000010", "/": "001001010100100",
    "?": "110001010000010", "'": "010010000000000", "+": "000010111010000",
}


def text_width(text: str, scale: int = 1) -> int:
    return max(0, len(text) * 4 * scale - scale)


def draw_text(canvas, x: int, y: int, text: str, color, scale: int = 1, shadow=None):
    """Draw onto an HxWx3 array, clipped to its edges; unknown characters show as '?'."""
    if shadow:
        draw_text(canvas, x + scale, y + scale, text, shadow, scale)
    h, w = canvas.shape[:2]
    for ch in text.upper():
        for i, bit in enumerate(GLYPHS.get(ch, GLYPHS["?"])):
            if bit == "1":
                px, py = x + (i % 3) * scale, y + (i // 3) * scale
                canvas[max(0, py) : min(h, py + scale), max(0, px) : min(w, px + scale)] = color
        x += 4 * scale
